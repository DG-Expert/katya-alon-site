// Copies the canonical `event:` block of content/workshop.yaml into worker/src/event.generated.js (build/deploy time).
// Usage: node scripts/sync-event.mjs          write the file
//        node scripts/sync-event.mjs --check  exit 1 if the file is stale
// No YAML dependency: the block is deliberately plain "key: value" lines and is validated strictly here.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const YAML = new URL('../content/workshop.yaml', import.meta.url);
const OUT = new URL('../worker/src/event.generated.js', import.meta.url);
const KEYS = ['workshop_id', 'timezone', 'first_session_date', 'second_session_date', 'session_count', 'total_hours'];

function realDate(s) {
  const d = new Date(`${s}T00:00:00Z`);
  return /^\d{4}-\d{2}-\d{2}$/.test(s) && !Number.isNaN(d.getTime()) && d.toISOString().startsWith(s);
}

export function parseEvent(yamlText) {
  const lines = yamlText.split(/\r?\n/);
  const start = lines.findIndex(l => l === 'event:');
  if (start < 0) throw new Error('content/workshop.yaml: missing top-level "event:" block');
  const raw = {};
  for (const line of lines.slice(start + 1)) {
    if (!/^\s+/.test(line)) break; // block ends at the next top-level line
    const m = line.match(/^  ([a-z_]+): *("[^"]*"|[^\s#"]+) *(?:#.*)?$/);
    if (!m) throw new Error(`event: unsupported line "${line.trim()}" (use plain "key: value")`);
    if (!KEYS.includes(m[1]) || m[1] in raw) throw new Error(`event: unknown or duplicate key "${m[1]}"`);
    raw[m[1]] = m[2].replace(/^"|"$/g, '');
  }
  for (const k of KEYS) if (!(k in raw)) throw new Error(`event: missing "${k}"`);
  const num = k => (/^\d+(\.\d+)?$/.test(raw[k]) ? Number(raw[k]) : NaN);
  const e = {
    workshopId: raw.workshop_id, timezone: raw.timezone, firstSessionDate: raw.first_session_date,
    secondSessionDate: raw.second_session_date === 'null' ? null : raw.second_session_date,
    sessionCount: num('session_count'), totalHours: num('total_hours')
  };
  if (!/^[A-Za-z0-9._-]{1,64}$/.test(e.workshopId)) throw new Error('event.workshop_id invalid');
  if (!/^[A-Za-z_]+(\/[A-Za-z_+\-0-9]+)+$/.test(e.timezone)) throw new Error('event.timezone invalid (e.g. Asia/Jerusalem)');
  if (!realDate(e.firstSessionDate)) throw new Error('event.first_session_date must be a real YYYY-MM-DD (quoted)');
  if (e.secondSessionDate !== null && (!realDate(e.secondSessionDate) || e.secondSessionDate <= e.firstSessionDate)) throw new Error('event.second_session_date must be null or a real date after the first');
  if (!Number.isInteger(e.sessionCount) || e.sessionCount < 1 || e.sessionCount > 20) throw new Error('event.session_count must be an integer 1-20');
  if (!(e.totalHours > 0 && e.totalHours <= 100)) throw new Error('event.total_hours must be a number 0-100');
  return e;
}

export const render = e => `// GENERATED by scripts/sync-event.mjs from content/workshop.yaml. Do not edit by hand.\nexport const EVENT = Object.freeze(${JSON.stringify(e, null, 2)});\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render(parseEvent(readFileSync(YAML, 'utf8')));
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing = stale */ }
    if (current !== out) { console.error('worker/src/event.generated.js is stale: run node scripts/sync-event.mjs'); process.exit(1); }
    console.log('event metadata in sync');
  } else {
    writeFileSync(OUT, out);
    console.log('wrote worker/src/event.generated.js');
  }
}
